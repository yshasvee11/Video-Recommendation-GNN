                    "        self.drop_rate = drop_rate\n",
                    "        self.num_edges = len(train_u)\n",
                    "        self.edge_scores_ema = np.ones(self.num_edges, dtype=np.float32)\n",
                    "        self.active_mask = np.ones(self.num_edges, dtype=bool)\n",
                    "\n",
                    "    def update_and_prune(self, model, dataset):\n",
                    "        model.eval()\n",
                    "        with torch.no_grad():\n",
                    "            h_u, h_v = model.get_bipartite_embeddings()\n",
                    "        hu_norm = F.normalize(h_u, dim=-1)\n",
                    "        hv_norm = F.normalize(h_v, dim=-1)\n",
                    "        u_t = torch.from_numpy(self.train_u).long().to(cfg.DEVICE)\n",
                    "        i_t = torch.from_numpy(self.train_i).long().to(cfg.DEVICE)\n",
                    "        with torch.no_grad():\n",
                    "            cos_sims = torch.sum(hu_norm[u_t] * hv_norm[i_t], dim=-1).cpu().numpy()\n",
                    "        self.edge_scores_ema = self.beta * self.edge_scores_ema + (1.0 - self.beta) * cos_sims\n",
                    "        active_indices = np.where(self.active_mask)[0]\n",
                    "        k_drop = int(self.drop_rate * len(active_indices))\n",
                    "        if k_drop > 0:\n",
                    "            sub_scores = self.edge_scores_ema[active_indices]\n",
                    "            lowest_sub_idx = np.argpartition(sub_scores, k_drop)[:k_drop]\n",
                    "            drop_indices = active_indices[lowest_sub_idx]\n",
                    "            self.active_mask[drop_indices] = False\n",
                    "        kept_u = self.train_u[self.active_mask]\n",
