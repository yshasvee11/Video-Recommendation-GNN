                    "        i_z2 = F.normalize(self.proj_item(i_emb + torch.randn_like(i_emb)*0.05), dim=-1)\n",
                    "        sim_u_pos = torch.sum(u_z1 * u_z2, dim=-1) / cfg.TEMPERATURE\n",
                    "        sim_u_all = torch.mm(u_z1, u_z2.t()) / cfg.TEMPERATURE\n",
                    "        loss_u = -torch.mean(sim_u_pos - torch.logsumexp(sim_u_all, dim=-1))\n",
                    "        sim_i_pos = torch.sum(i_z1 * i_z2, dim=-1) / cfg.TEMPERATURE\n",
                    "        sim_i_all = torch.mm(i_z1, i_z2.t()) / cfg.TEMPERATURE\n",
