                    "def compute_genre_diversity(item_ids, genre_list):\n",
                    "    n = len(item_ids)\n",
                    "    if n < 2:\n",
                    "        return 1.0\n",
                    "    genres = [genre_list[i] for i in item_ids]\n",
                    "    counts = {}\n",
                    "    for g in genres:\n",
                    "        counts[g] = counts.get(g, 0) + 1\n",
                    "    same_pairs = sum(c * (c - 1) for c in counts.values() if c > 1)\n",
                    "    return 1.0 - (same_pairs / (n * (n - 1)))\n",
                    "\n",
                    "def evaluate_model_paper3_protocol(model, dataset, eval_mode='test', topk=cfg.TOP_K, lambda_div=0.0, sample_users=None):\n",
                    "    '''\n",
                    "    Exact Paper 3 (HetGNN / HHFAN / MPGCL) Protocol:\n",
                    "    For each test user, their positive items are ranked together with 100 randomly sampled unobserved negative items.\n",
                    "    This directly matches Table 2 and Table 5 of Paper 3.\n",
                    "    '''\n",
                    "    model.eval()\n",
                    "    with torch.no_grad():\n",
                    "        h_u, h_v = model.forward()\n",
                    "    target_pos = dataset.test_pos_set if eval_mode == 'test' else dataset.val_pos_set\n",
                    "    train_pos = dataset.train_pos_set\n",
                    "    eval_users = [u for u in range(dataset.n_users) if len(target_pos[u]) > 0]\n",
                    "    if sample_users is not None and sample_users < len(eval_users):\n",
                    "        np.random.seed(cfg.SEED)\n",
                    "        eval_users = np.random.choice(eval_users, sample_users, replace=False)\n",
                    "        \n",
                    "    precisions, recalls, ndcgs, aucs, divs = [], [], [], [], []\n",
                    "    for u in eval_users:\n",
                    "        pos_items = list(target_pos[u])\n",
                    "        train_items = train_pos[u]\n",
                    "        negs = []\n",
                    "        while len(negs) < 100:\n",
                    "            neg = np.random.randint(0, dataset.n_items)\n",
                    "            if neg not in train_items and neg not in target_pos[u]:\n",
                    "                negs.append(neg)\n",
