                    "import torch.nn as nn\n",
                    "import torch.nn.functional as F\n",
                    "\n",
                    "class BipartiteGraphDenoiser:\n",
                    "    def __init__(self, train_u, train_i, n_users, n_items, beta_ema=cfg.DENOISE_EMA_BETA, drop_rate=cfg.DENOISE_DROP_RATE):\n",
